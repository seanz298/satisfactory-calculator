const assert=require('node:assert/strict'),vm=require('node:vm'),{environment}=require('./integration.cjs'),Files=require('../src/plan-files.js');
const c=environment();
vm.runInContext(`let workshop=emptyWorkspace();
const a=fresh();a.planUid='a';a.supplies=[{id:'Desc_OreIron_C',q:100,stop:true}];a.products=[{id:'Desc_IronIngot_C',q:100,lock:true}];
const b=fresh();b.planUid='b';b.products=[{id:'Desc_IronPlate_C',q:40,lock:true}];b.liveLinks=[{id:'ab',from:'a',item:'Desc_IronIngot_C',rate:60}];
const c=fresh();c.planUid='c';c.products=[{id:'Desc_IronPlate_C',q:20,lock:true}];c.liveLinks=[{id:'ac',from:'a',item:'Desc_IronIngot_C',rate:40}];
workshop.plans=[{id:1,name:'源工厂',state:a},{id:2,name:'接收一',state:b},{id:3,name:'接收二',state:c}];workshop.active={id:2,name:'接收一'};state=b;`,c);
const get=code=>vm.runInContext(code,c);
assert(get('planSolve(demands(),state).ok'));
assert(Math.abs(get("summarize(planSolve(demands(),state)).external.Desc_IronIngot_C")-60)<1e-6);
get("a.products[0].q=80");
assert.equal(get('planSolve(demands(),state).ok'),false);
assert.equal(get("evaluateLivePlans().allocations.get('b:ab').actual"),48);
get("b.mode='reverse'");assert.equal(get('planSolve(demands(),state).ok'),false,'reverse must not invent linked supplies');
get("a.products[0].q=100;b.mode='forward'");
assert.throws(()=>get("addLivePlanLink('b','a','Desc_IronPlate_C',1)"),/循环依赖/);
assert.equal(get('a.liveLinks.length'),0);
get("a.products[0].sink=true");
assert.equal(get("evaluateLivePlans().results.get('a').exports.Desc_IronIngot_C || 0"),0,'sink targets cannot be exported a second time');
get("delete a.products[0].sink");
const exported=get('JSON.stringify(workspacePayload())');c.saved=JSON.parse(exported);
get('const restored=normalizeWorkspace(saved);workshop=restored.w;state=restored.s');
assert(get('planSolve(demands(),state).ok'),'workspace round trip');
get("workshop.plans=workshop.plans.filter(p=>p.state.planUid!=='a')");
assert.equal(get('planSolve(demands(),state).ok'),false,'missing sources fail closed');
const make=(uid,links=[])=>({name:uid,state:{version:12,planUid:uid,liveLinks:links}});
const existing={active:{name:'edit'},plans:[{id:1,...make('a')}],nextId:2};
const merged=Files.merge(existing,[make('a'),make('b',[{id:'link',from:'a',item:'iron',rate:10}])]);
assert.notEqual(merged.plans[1].state.planUid,'a');assert.equal(merged.plans[2].state.liveLinks[0].from,merged.plans[1].state.planUid);
// Draft source edits survive switching and a browser-storage round trip.
get("workshop=emptyWorkspace();workshop.plans=[{id:1,name:'source',state:a},{id:2,name:'receiver',state:b},{id:3,name:'other',state:c}];workshop.active={id:1,name:'source'};state=JSON.parse(JSON.stringify(a));state.products[0].q=70");
c.saved=JSON.parse(get('JSON.stringify(workspacePayload())'));
get("const restoredAgain=normalizeWorkspace(saved);workshop=restoredAgain.w;state=workshop.plans.find(p=>p.state.planUid==='b').state");
assert.equal(get("evaluateLivePlans().allocations.get('b:ab').actual"),42);
assert.equal(get('planSolve(demands(),state).ok'),false);
// Removing the active supplier must not keep supplying via its editable draft.
get("state=JSON.parse(JSON.stringify(workshop.plans[0].state));workshop.active={id:1,name:'source'};removeNamedPlan(1)");
assert.notEqual(get('state.planUid'),'a');
assert.equal(get("workshop.liveDrafts.a"),undefined);
assert.equal(get("evaluateLivePlans().results.get('b')?.ok"),undefined);
assert(get("evaluateLivePlans().errors.some(e=>e.plan==='b' && e.message.includes('来源方案不存在'))"));
c.saved=JSON.parse(get('JSON.stringify(workspacePayload())'));
get('const afterDelete=normalizeWorkspace(saved);workshop=afterDelete.w;state=afterDelete.s');
assert(get("evaluateLivePlans().errors.some(e=>e.plan==='b')"),'deleted source remains missing after reload');
get("state.planUid='a'");
assert(get("evaluateLivePlans().errors.some(e=>e.plan==='b' && e.message.includes('已删除'))"),'restoring an old draft cannot resurrect a deleted supplier');
console.log('Actual solver: finite live inputs, real-time source edits, reverse limits, cycle rollback, persistence, deletion and import identity PASS');
