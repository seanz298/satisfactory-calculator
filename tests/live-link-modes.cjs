const assert = require('node:assert/strict'), vm = require('node:vm');
const {environment} = require('./integration.cjs');
const c = environment(), run = code => vm.runInContext(code, c);
run(`let workshop=emptyWorkspace();
const source=fresh();source.planUid='powder';source.mode='reverse';
source.products=[{id:'Desc_CopperDust_C',q:200,lock:true}];
const receiver=fresh();receiver.planUid='pasta';receiver.mode='reverse';
receiver.supplies=[{id:'Desc_CopperDust_C',q:999,stop:false}];
receiver.products=[{id:'Desc_SpaceElevatorPart_9_C',q:5,lock:true}];
receiver.liveLinks=[{id:'powder-in',from:'powder',item:'Desc_CopperDust_C',rate:200}];
workshop.plans=[{id:1,name:'powder',state:source},{id:2,name:'pasta',state:receiver}];
workshop.active={id:2,name:'pasta'};state=receiver;`);
let r = run(`(()=>{const solution=planSolve(demands(),state),p=summarize(solution);return {ok:solution.ok,external:p?.external.Desc_CopperDust_C,produced:p?.rows.reduce((n,r)=>n+(r.outs.Desc_CopperDust_C||0),0)}})()`);
assert(r.ok); assert(Math.abs(r.external-200)<1e-5); assert(r.produced>0);
run('source.products[0].q=100');
r = run(`(()=>{const p=summarize(planSolve(demands(),state));return {external:p.external.Desc_CopperDust_C,produced:p.rows.reduce((n,r)=>n+(r.outs.Desc_CopperDust_C||0),0)}})()`);
assert(Math.abs(r.external-100)<1e-5); assert(r.produced>200);
run('receiver.supplies[0].stop=true');
assert.equal(run('planSolve(demands(),state).ok'),false,'boundary supplies cannot manufacture missing linked input');
// A linked raw material is finite in reverse and constrained modes.
run(`source.products=[{id:'Desc_OreIron_C',q:100,lock:true}];
receiver.products=[{id:'Desc_IronPlate_C',q:80,lock:true}];
receiver.supplies=[];receiver.liveLinks=[{id:'ore-in',from:'powder',item:'Desc_OreIron_C',rate:100}];`);
assert.equal(run('planSolve(demands(),state).ok'),false);
run(`receiver.mode='constrained';receiver.inputConstraint={id:'Desc_OreIron_C',q:1000}`);
assert.equal(run('planSolve(demands(),state).ok'),false,'constraint cannot enlarge a live allocation');
run('receiver.products[0].q=60');
assert(run('planSolve(demands(),state).ok'));
assert.throws(()=>run("addLivePlanLink('powder','pasta','Desc_OreIron_C',10)"),/已存在/);
run("receiver.supplies=[{id:'Desc_IronIngot_C',q:10,stop:true,lock:true}]");
assert.throws(()=>run("addLivePlanLink('powder','pasta','Desc_IronIngot_C',10)"),/锁定/);
// Downstream output disappears when any upstream factory becomes infeasible.
run(`receiver.mode='reverse';receiver.products=[{id:'Desc_IronPlate_C',q:60,lock:true}];receiver.supplies=[];
const third=fresh();third.planUid='third';third.mode='reverse';third.products=[{id:'Desc_IronPlateReinforced_C',q:1,lock:true}];
third.liveLinks=[{id:'plate-in',from:'pasta',item:'Desc_IronPlate_C',rate:60}];
workshop.plans.push({id:3,name:'third',state:third});`);
assert(run("evaluateLivePlans().results.get('third').ok"));
run('source.products[0].q=50');
assert.equal(run("evaluateLivePlans().results.get('third')?.ok"),undefined);
assert(run("evaluateLivePlans().errors.some(e=>e.plan==='third'&&e.message.includes('来源方案不可行'))"));
console.log('Live partial production, raw reverse/constrained caps, duplicate/lock protection and multihop failures PASS');
